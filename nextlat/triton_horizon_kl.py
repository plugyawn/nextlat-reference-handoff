"""Fused first-order KL epilogue for the d=4 shared-teacher path.

This module deliberately fuses only the bandwidth-bound elementwise portion of
the objective.  The vocabulary GEMMs and PyTorch's FP32 log-softmax remain the
authority operations.  Given student log-probabilities and compact indices into
the exact teacher rows, two Triton launches compute:

* the full-vocabulary tokenwise ``KL(teacher || student)``;
* the exact log-softmax gradient ``p_student * sum(p_teacher) - p_teacher``;
* a low-precision probability-delta tensor for the existing vocabulary-head
  transpose GEMM.

Teacher rows are loaded indirectly, so four recurrent horizons no longer
materialize a dense repeated ``[student_rows, vocab]`` teacher tensor.  There is
no CPU or eager fallback: the corresponding training backend is explicitly a
CUDA/Triton-only systems optimization and fails closed otherwise.
"""

from __future__ import annotations

import torch

try:
    import triton
    import triton.language as tl
    from triton.language.extra import libdevice
except ImportError:  # pragma: no cover - exercised by the fail-closed CPU test
    triton = None
    tl = None
    libdevice = None


_VOCAB_BLOCK = 4096


if triton is not None:

    @triton.jit
    def _kl_mass_partials(
        student_log_probs,
        teacher_log_probs,
        teacher_rows,
        partial_mass,
        partial_kl,
        vocab_size: tl.constexpr,
        num_tiles: tl.constexpr,
        BLOCK_V: tl.constexpr,
    ):
        row = tl.program_id(axis=0)
        tile = tl.program_id(axis=1)
        columns = tile * BLOCK_V + tl.arange(0, BLOCK_V)
        valid = columns < vocab_size
        teacher_row = tl.load(teacher_rows + row)

        student = tl.load(
            student_log_probs + row * vocab_size + columns,
            mask=valid,
            other=0.0,
        ).to(tl.float32)
        teacher = tl.load(
            teacher_log_probs + teacher_row * vocab_size + columns,
            mask=valid,
            other=-float("inf"),
        ).to(tl.float32)
        teacher_probability = libdevice.exp(teacher)

        partial_offset = row * num_tiles + tile
        tl.store(
            partial_mass + partial_offset,
            tl.sum(teacher_probability, axis=0),
        )
        tl.store(
            partial_kl + partial_offset,
            tl.sum(
                tl.where(
                    valid,
                    teacher_probability * (teacher - student),
                    0.0,
                ),
                axis=0,
            ),
        )

    @triton.jit
    def _kl_delta_from_partials(
        student_log_probs,
        teacher_log_probs,
        teacher_rows,
        partial_mass,
        partial_kl,
        tokenwise_kl,
        probability_delta,
        vocab_size: tl.constexpr,
        num_tiles: tl.constexpr,
        BLOCK_V: tl.constexpr,
        BLOCK_PARTIALS: tl.constexpr,
    ):
        row = tl.program_id(axis=0)
        tile = tl.program_id(axis=1)
        partial_columns = tl.arange(0, BLOCK_PARTIALS)
        partial_valid = partial_columns < num_tiles
        partial_base = row * num_tiles + partial_columns
        teacher_mass = tl.sum(
            tl.load(partial_mass + partial_base, mask=partial_valid, other=0.0),
            axis=0,
        )
        total_kl = tl.sum(
            tl.load(partial_kl + partial_base, mask=partial_valid, other=0.0),
            axis=0,
        )

        columns = tile * BLOCK_V + tl.arange(0, BLOCK_V)
        valid = columns < vocab_size
        teacher_row = tl.load(teacher_rows + row)
        student = tl.load(
            student_log_probs + row * vocab_size + columns,
            mask=valid,
            other=-float("inf"),
        ).to(tl.float32)
        teacher = tl.load(
            teacher_log_probs + teacher_row * vocab_size + columns,
            mask=valid,
            other=-float("inf"),
        ).to(tl.float32)
        delta = libdevice.exp(student) * teacher_mass - libdevice.exp(teacher)
        tl.store(
            probability_delta + row * vocab_size + columns,
            delta,
            mask=valid,
        )
        # Every tile has the same cheap partial reduction.  A predicated store
        # avoids a third launch solely for the rowwise KL output.
        tl.store(tokenwise_kl + row, total_kl, mask=tile == 0)


def triton_tokenwise_kl_and_probability_delta(
    *,
    student_log_probs: torch.Tensor,
    teacher_log_probs: torch.Tensor,
    teacher_rows: torch.Tensor,
    delta_dtype: torch.dtype,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Return full-vocabulary tokenwise KL and detached-head logit gradient.

    ``teacher_rows`` maps each student row to one row in
    ``teacher_log_probs``.  It is generated by the trusted d=4 mask schedule;
    avoiding a value-dependent host assertion here is part of the hot-path
    contract.  Shapes, devices, layouts, and dtypes are checked synchronously.
    """

    if triton is None:
        raise RuntimeError("shared_teacher_horizon_stacked_triton requires Triton")
    if not (
        student_log_probs.is_cuda and teacher_log_probs.is_cuda and teacher_rows.is_cuda
    ):
        raise RuntimeError(
            "shared_teacher_horizon_stacked_triton requires CUDA tensors"
        )
    if student_log_probs.ndim != 2 or teacher_log_probs.ndim != 2:
        raise ValueError("student and teacher log-probabilities must be rank two")
    if student_log_probs.shape[1] != teacher_log_probs.shape[1]:
        raise ValueError("student and teacher vocabulary sizes must match")
    if teacher_rows.ndim != 1 or teacher_rows.shape[0] != student_log_probs.shape[0]:
        raise ValueError("teacher_rows must provide one index per student row")
    if student_log_probs.dtype != torch.float32:
        raise ValueError("student log-probabilities must be FP32")
    if teacher_log_probs.dtype != torch.float32:
        raise ValueError("teacher log-probabilities must be FP32")
    if teacher_rows.dtype not in (torch.int32, torch.int64):
        raise ValueError("teacher_rows must use int32 or int64 indices")
    if delta_dtype not in (torch.bfloat16, torch.float16, torch.float32):
        raise ValueError("probability delta must use BF16, FP16, or FP32")
    if not (
        student_log_probs.is_contiguous()
        and teacher_log_probs.is_contiguous()
        and teacher_rows.is_contiguous()
    ):
        raise ValueError("fused KL inputs must be contiguous")

    rows, vocab_size = student_log_probs.shape
    if rows == 0 or vocab_size == 0:
        raise ValueError("fused KL requires nonempty rows and vocabulary")
    num_tiles = triton.cdiv(vocab_size, _VOCAB_BLOCK)
    partials = torch.empty(
        (2, rows, num_tiles),
        dtype=torch.float32,
        device=student_log_probs.device,
    )
    tokenwise_kl = torch.empty(
        (rows,), dtype=torch.float32, device=student_log_probs.device
    )
    probability_delta = torch.empty(
        student_log_probs.shape,
        dtype=delta_dtype,
        device=student_log_probs.device,
    )
    grid = (rows, num_tiles)
    _kl_mass_partials[grid](
        student_log_probs,
        teacher_log_probs,
        teacher_rows,
        partials[0],
        partials[1],
        vocab_size=vocab_size,
        num_tiles=num_tiles,
        BLOCK_V=_VOCAB_BLOCK,
        num_warps=8,
        num_stages=2,
    )
    _kl_delta_from_partials[grid](
        student_log_probs,
        teacher_log_probs,
        teacher_rows,
        partials[0],
        partials[1],
        tokenwise_kl,
        probability_delta,
        vocab_size=vocab_size,
        num_tiles=num_tiles,
        BLOCK_V=_VOCAB_BLOCK,
        BLOCK_PARTIALS=triton.next_power_of_2(num_tiles),
        num_warps=8,
        num_stages=2,
    )
    return tokenwise_kl, probability_delta


def triton_runtime_available() -> bool:
    """Whether the Python runtime can construct the explicit Triton backend."""

    return triton is not None
